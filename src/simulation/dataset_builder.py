"""
Dataset Builder — Phase A synthetic training dataset orchestration.

Loads all SOPs from data/sops/, generates N clips per scenario type per SOP,
applies augmentation to each clip, saves MP4 video files + a JSON label index.

Output structure:
    data/synthetic/
        {sop_id}/
            {scenario_type}/
                {clip_id}.mp4         — synthetic video clip
                {clip_id}.json        — ClipLabel metadata
        dataset_index.json            — master index of all clips

Usage (CLI):
    python -m src.simulation.dataset_builder

Usage (programmatic):
    from src.simulation.dataset_builder import DatasetBuilder
    builder = DatasetBuilder()
    stats = builder.build()
"""
from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path

import cv2
import numpy as np

from src.simulation.augmentation import AugmentationConfig, VideoAugmentor
from src.simulation.scenario_generator import (
    FRAME_HEIGHT,
    FRAME_WIDTH,
    FPS,
    ScenarioGenerator,
    ScenarioType,
)
from src.simulation.sop_parser import load_all_sops
from src.simulation.sop_schema import SOP

logger = logging.getLogger(__name__)

# ── Default paths ──────────────────────────────────────────────────────────

_PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
_DEFAULT_SOPS_DIR = _PROJECT_ROOT / "data" / "sops"
_DEFAULT_OUTPUT_DIR = _PROJECT_ROOT / "data" / "synthetic"

# ── Config ─────────────────────────────────────────────────────────────────

@dataclass
class DatasetConfig:
    """Controls how many clips are generated and where they are saved."""

    sops_dir: Path = _DEFAULT_SOPS_DIR
    output_dir: Path = _DEFAULT_OUTPUT_DIR

    # Number of clips generated per (SOP × scenario_type) combination
    clips_per_scenario: int = 20

    # Number of augmented copies produced for each base clip
    augmented_copies_per_clip: int = 3

    # Random seed — fixed for reproducibility (Rules.md §1.5)
    seed: int = 42

    # Video codec — MJPG in AVI gives broadest cross-platform compatibility
    # Switch to "mp4v" for .mp4 output if H.264 is available on the host
    codec: str = "MJPG"
    container_ext: str = ".avi"


@dataclass
class DatasetStats:
    """Summary statistics returned after a build run."""

    total_clips: int = 0
    total_frames: int = 0
    clips_by_scenario: dict[str, int] = None
    clips_by_sop: dict[str, int] = None
    errors: list[str] = None

    def __post_init__(self) -> None:
        if self.clips_by_scenario is None:
            self.clips_by_scenario = {}
        if self.clips_by_sop is None:
            self.clips_by_sop = {}
        if self.errors is None:
            self.errors = []

    def to_dict(self) -> dict:
        return {
            "total_clips": self.total_clips,
            "total_frames": self.total_frames,
            "clips_by_scenario": self.clips_by_scenario,
            "clips_by_sop": self.clips_by_sop,
            "errors": self.errors,
        }


# ── Builder ────────────────────────────────────────────────────────────────

class DatasetBuilder:
    """
    Orchestrates synthetic dataset generation for all SOPs and scenario types.

    Each clip is:
        1. Generated by ScenarioGenerator (base clip)
        2. Augmented N times by VideoAugmentor (augmented copies)
        3. Saved as a video file + JSON label
    """

    ALL_SCENARIOS = list(ScenarioType)

    def __init__(self, config: DatasetConfig | None = None) -> None:
        self.config = config or DatasetConfig()
        self._generator = ScenarioGenerator(seed=self.config.seed)
        self._augmentor = VideoAugmentor(
            config=AugmentationConfig(),
            seed=self.config.seed,
        )

    def build(self) -> DatasetStats:
        """
        Run the full dataset build pipeline.

        Returns:
            DatasetStats summarising what was generated.
        """
        stats = DatasetStats()
        all_labels: list[dict] = []

        # ── Load SOPs ──────────────────────────────────────────────────────
        try:
            sops = load_all_sops(self.config.sops_dir)
        except (FileNotFoundError, ValueError) as exc:
            stats.errors.append(f"Failed to load SOPs: {exc}")
            return stats

        if not sops:
            stats.errors.append(f"No SOP files found in {self.config.sops_dir}")
            return stats

        logger.info("Loaded %d SOP(s): %s", len(sops), list(sops.keys()))

        # ── Generate clips ─────────────────────────────────────────────────
        for sop in sops.values():
            sop_stats = self._build_sop(sop, all_labels, stats)
            stats.clips_by_sop[sop.id] = sop_stats

        # ── Write master index ─────────────────────────────────────────────
        self.config.output_dir.mkdir(parents=True, exist_ok=True)
        index_path = self.config.output_dir / "dataset_index.json"
        with open(index_path, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "stats": stats.to_dict(),
                    "clips": all_labels,
                },
                f,
                indent=2,
                ensure_ascii=False,
            )
        logger.info("Dataset index written to %s", index_path)

        return stats

    def _build_sop(
        self,
        sop: SOP,
        all_labels: list[dict],
        stats: DatasetStats,
    ) -> int:
        """Generate all clips for a single SOP. Returns number of clips created."""
        clips_created = 0

        for scenario in self.ALL_SCENARIOS:
            for clip_num in range(self.config.clips_per_scenario):
                try:
                    clips_created += self._generate_and_save(
                        sop, scenario, clip_num, all_labels, stats
                    )
                except Exception as exc:
                    msg = (
                        f"Error generating {sop.id}/{scenario.value} "
                        f"clip {clip_num}: {exc}"
                    )
                    logger.warning(msg)
                    stats.errors.append(msg)

        return clips_created

    def _generate_and_save(
        self,
        sop: SOP,
        scenario: ScenarioType,
        clip_num: int,
        all_labels: list[dict],
        stats: DatasetStats,
    ) -> int:
        """Generate one base clip + augmented copies. Returns number saved."""
        frames, label = self._generator.generate_clip(sop, scenario)

        # Prepare output directory
        out_dir = self.config.output_dir / sop.id / scenario.value
        out_dir.mkdir(parents=True, exist_ok=True)

        saved = 0

        # ── Base clip ──────────────────────────────────────────────────────
        base_path = out_dir / f"{label.clip_id}{self.config.container_ext}"
        self._save_clip(frames, base_path)
        label_dict = label.to_dict()
        label_dict["file"] = str(base_path.relative_to(self.config.output_dir))
        label_dict["augmented"] = False
        all_labels.append(label_dict)
        stats.total_clips += 1
        stats.total_frames += len(frames)
        stats.clips_by_scenario[scenario.value] = (
            stats.clips_by_scenario.get(scenario.value, 0) + 1
        )
        saved += 1

        # ── Augmented copies ───────────────────────────────────────────────
        for aug_idx in range(self.config.augmented_copies_per_clip):
            aug_frames = self._augmentor.augment_clip(frames)
            aug_path = out_dir / f"{label.clip_id}_aug{aug_idx}{self.config.container_ext}"
            self._save_clip(aug_frames, aug_path)

            aug_label = dict(label_dict)
            aug_label["file"] = str(aug_path.relative_to(self.config.output_dir))
            aug_label["augmented"] = True
            aug_label["aug_index"] = aug_idx
            all_labels.append(aug_label)
            stats.total_clips += 1
            stats.total_frames += len(aug_frames)
            stats.clips_by_scenario[scenario.value] = (
                stats.clips_by_scenario.get(scenario.value, 0) + 1
            )
            saved += 1

        # ── Individual label JSON ──────────────────────────────────────────
        json_path = out_dir / f"{label.clip_id}.json"
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(label_dict, f, indent=2, ensure_ascii=False)

        return saved

    def _save_clip(self, frames: list[np.ndarray], path: Path) -> None:
        """Write a list of BGR frames to a video file."""
        if not frames:
            raise ValueError(f"Cannot save empty frame list to {path}")

        fourcc = cv2.VideoWriter_fourcc(*self.config.codec)
        writer = cv2.VideoWriter(
            str(path),
            fourcc,
            float(FPS),
            (FRAME_WIDTH, FRAME_HEIGHT),
        )
        try:
            for frame in frames:
                writer.write(frame)
        finally:
            writer.release()

        if not path.exists() or path.stat().st_size == 0:
            raise IOError(f"VideoWriter produced an empty file at {path}")


# ── CLI entry point ────────────────────────────────────────────────────────

if __name__ == "__main__":
    import sys

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    )

    config = DatasetConfig()

    # Allow quick override from CLI: python -m src.simulation.dataset_builder 5
    if len(sys.argv) > 1:
        config.clips_per_scenario = int(sys.argv[1])

    logger.info(
        "Starting dataset build: sops_dir=%s, clips/scenario=%d, aug_copies=%d",
        config.sops_dir,
        config.clips_per_scenario,
        config.augmented_copies_per_clip,
    )

    builder = DatasetBuilder(config)
    stats = builder.build()

    print("\n-- Dataset Build Complete ------------------------------------------")
    print(f"  Total clips   : {stats.total_clips}")
    print(f"  Total frames  : {stats.total_frames}")
    print(f"  By scenario   : {stats.clips_by_scenario}")
    print(f"  By SOP        : {stats.clips_by_sop}")
    if stats.errors:
        print(f"  Errors ({len(stats.errors)}): ")
        for err in stats.errors:
            print(f"    - {err}")
    print("--------------------------------------------------------------------\n")
