"""
PyTorch Datasets for FORGE-Vision training.

SyntheticSOPDataset  — reads Phase A clips from data/synthetic/
RealSOPDataset       — reads Phase B clips from data/real/ (Phase 3+)
"""
from __future__ import annotations

import json
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import cv2
import numpy as np
import torch
from torch.utils.data import Dataset

# ── Label encoding ─────────────────────────────────────────────────────────

SCENARIO_TO_IDX: dict[str, int] = {
    "correct": 0,
    "missing_step": 1,
    "wrong_order": 2,
    "unsafe": 3,
    "rare_failure": 4,
}
IDX_TO_SCENARIO = {v: k for k, v in SCENARIO_TO_IDX.items()}

ERROR_TYPE_TO_IDX: dict[str, int] = {
    "CORRECT": 0,
    "MISSING_STEP": 1,
    "WRONG_ORDER": 2,
    "INCORRECT_EXECUTION": 3,
    "MISSING_PPE": 4,
    "UNSAFE_POSTURE": 5,
    "TIMEOUT": 6,
}


# ── Clip record ────────────────────────────────────────────────────────────

@dataclass
class ClipRecord:
    """Lightweight record pointing to one clip on disk."""
    clip_id: str
    file_path: Path
    sop_id: str
    scenario_type: str
    scenario_idx: int
    executed_steps: list[int]
    error_step_id: Optional[int]
    error_type: Optional[str]
    augmented: bool


# ── Dataset ────────────────────────────────────────────────────────────────

class SyntheticSOPDataset(Dataset):
    """
    PyTorch Dataset that reads synthetic video clips generated by DatasetBuilder.

    Each item returns a (frames_tensor, label_dict) pair where:
        frames_tensor: FloatTensor of shape (T, C, H, W) — T sampled frames
        label_dict:    dict with scenario_idx, error_type_idx, sop_id, step info

    Args:
        index_path:      Path to dataset_index.json produced by DatasetBuilder.
        num_frames:      Number of frames to uniformly sample from each clip.
        frame_size:      (H, W) to resize each frame to.
        augmented_only:  If True, only include augmented clips (not base clips).
        split:           "train", "val", or "test".
        val_split:       Fraction reserved for validation.
        test_split:      Fraction reserved for test.
        seed:            Random seed for reproducible split.
        transform:       Optional torchvision transform applied per frame.
    """

    def __init__(
        self,
        index_path: str | Path,
        num_frames: int = 16,
        frame_size: tuple[int, int] = (224, 224),
        augmented_only: bool = False,
        split: str = "train",
        val_split: float = 0.15,
        test_split: float = 0.10,
        seed: int = 42,
        transform=None,
    ) -> None:
        self.index_path = Path(index_path)
        self.data_dir = self.index_path.parent
        self.num_frames = num_frames
        self.frame_size = frame_size
        self.split = split
        self.transform = transform

        if split not in ("train", "val", "test"):
            raise ValueError(f"split must be 'train', 'val', or 'test', got '{split}'")

        all_records = self._load_index(augmented_only)
        self.records = self._split_records(all_records, val_split, test_split, seed)

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, dict]:
        record = self.records[idx]
        frames = self._load_frames(record.file_path)
        frames_tensor = self._frames_to_tensor(frames)

        label = {
            "scenario_idx": torch.tensor(record.scenario_idx, dtype=torch.long),
            "scenario_type": record.scenario_type,
            "sop_id": record.sop_id,
            "executed_steps": torch.tensor(record.executed_steps, dtype=torch.long),
            "error_step_id": torch.tensor(
                record.error_step_id if record.error_step_id is not None else -1,
                dtype=torch.long,
            ),
            "error_type_idx": torch.tensor(
                ERROR_TYPE_TO_IDX.get(record.error_type or "CORRECT", 0),
                dtype=torch.long,
            ),
            "augmented": record.augmented,
        }
        return frames_tensor, label

    # ── Internal helpers ───────────────────────────────────────────────────

    def _load_index(self, augmented_only: bool) -> list[ClipRecord]:
        if not self.index_path.exists():
            raise FileNotFoundError(f"Dataset index not found: {self.index_path}")

        with open(self.index_path, encoding="utf-8") as f:
            raw = json.load(f)

        records: list[ClipRecord] = []
        for item in raw.get("clips", []):
            if augmented_only and not item.get("augmented", False):
                continue

            file_path = self.data_dir / item["file"]
            if not file_path.exists():
                continue  # skip missing files gracefully

            scenario = item.get("scenario_type", "correct")
            records.append(ClipRecord(
                clip_id=item["clip_id"],
                file_path=file_path,
                sop_id=item["sop_id"],
                scenario_type=scenario,
                scenario_idx=SCENARIO_TO_IDX.get(scenario, 0),
                executed_steps=item.get("executed_steps", []),
                error_step_id=item.get("error_step_id"),
                error_type=item.get("error_type"),
                augmented=item.get("augmented", False),
            ))

        return records

    def _split_records(
        self,
        records: list[ClipRecord],
        val_split: float,
        test_split: float,
        seed: int,
    ) -> list[ClipRecord]:
        rng = random.Random(seed)
        shuffled = list(records)
        rng.shuffle(shuffled)

        n = len(shuffled)
        n_test = max(1, int(n * test_split))
        n_val = max(1, int(n * val_split))
        n_train = n - n_val - n_test

        if self.split == "train":
            return shuffled[:n_train]
        elif self.split == "val":
            return shuffled[n_train : n_train + n_val]
        else:
            return shuffled[n_train + n_val :]

    def _load_frames(self, path: Path) -> list[np.ndarray]:
        cap = cv2.VideoCapture(str(path))
        all_frames: list[np.ndarray] = []
        try:
            while True:
                ret, frame = cap.read()
                if not ret:
                    break
                all_frames.append(frame)
        finally:
            cap.release()

        if not all_frames:
            # Return blank frames if file is unreadable
            h, w = self.frame_size
            return [np.zeros((h, w, 3), dtype=np.uint8)] * self.num_frames

        return self._sample_frames(all_frames)

    def _sample_frames(self, frames: list[np.ndarray]) -> list[np.ndarray]:
        """Uniformly sample exactly num_frames from the clip."""
        n = len(frames)
        if n == self.num_frames:
            return frames
        if n < self.num_frames:
            # Repeat last frame to pad
            pad = [frames[-1]] * (self.num_frames - n)
            return frames + pad
        # Uniform sampling
        indices = np.linspace(0, n - 1, self.num_frames, dtype=int)
        return [frames[i] for i in indices]

    def _frames_to_tensor(self, frames: list[np.ndarray]) -> torch.Tensor:
        """Convert list of BGR frames to (T, C, H, W) float tensor in [0, 1]."""
        h, w = self.frame_size
        tensors: list[torch.Tensor] = []

        for frame in frames:
            resized = cv2.resize(frame, (w, h), interpolation=cv2.INTER_LINEAR)
            rgb = cv2.cvtColor(resized, cv2.COLOR_BGR2RGB)
            t = torch.from_numpy(rgb).float() / 255.0   # (H, W, C)
            t = t.permute(2, 0, 1)                       # (C, H, W)

            if self.transform is not None:
                t = self.transform(t)

            tensors.append(t)

        return torch.stack(tensors, dim=0)  # (T, C, H, W)

    @property
    def num_classes(self) -> int:
        return len(SCENARIO_TO_IDX)

    @property
    def class_names(self) -> list[str]:
        return list(SCENARIO_TO_IDX.keys())
